#!/bin/bash
# Builds "Charness.app" (a small stay-open AppleScript applet) that starts the server and opens
# a window, and stops the server when you Quit it. Run this on your Mac:
#     ./scripts/make-mac-app.sh                  # installs to ~/Applications
#     ./scripts/make-mac-app.sh /some/folder     # or somewhere else
# The app points at THIS folder, so keep the folder where it is (re-run this script if you move it).
set -eu

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LAUNCHER="$HERE/scripts/launch.sh"

esc() { local s="$1"; s="${s//\\/\\\\}"; s="${s//\"/\\\"}"; printf '%s' "$s"; }

applescript() {
  cat <<APPLESCRIPT
-- Charness launcher (generated by scripts/make-mac-app.sh)
property launcher : "$(esc "$LAUNCHER")"

on run
	try
		do shell script (quoted form of launcher) & " start"
	on error errMsg
		display alert "Charness couldn't start" message errMsg as critical
		quit
	end try
end run

-- clicking the Dock icon again re-opens the window
on reopen
	try
		do shell script (quoted form of launcher) & " open"
	end try
end reopen

-- Cmd-Q / Dock > Quit stops the server too
on quit
	try
		do shell script (quoted form of launcher) & " stop"
	end try
	continue quit
end quit
APPLESCRIPT
}

if [ "${1:-}" = "--print-script" ]; then applescript; exit 0; fi

if [ "$(uname)" != Darwin ]; then echo "This builds a macOS app, so run it on your Mac." >&2; exit 1; fi
command -v osacompile >/dev/null 2>&1 || { echo "osacompile not found (it ships with macOS)." >&2; exit 1; }
if [ ! -d "$HERE/node_modules/@anthropic-ai/claude-agent-sdk" ]; then
  echo "Run 'npm install' in $HERE first." >&2; exit 1
fi

DEST="${1:-$HOME/Applications}"
APP="$DEST/Charness.app"
mkdir -p "$DEST"
chmod +x "$LAUNCHER"
SRC="$(mktemp -t charness-applet).applescript"
applescript > "$SRC"
rm -rf "$APP"
osacompile -s -o "$APP" "$SRC"
rm -f "$SRC"
echo "Built: $APP"
echo "Open it from Finder/Spotlight. First launch may ask permission to access folders; that's macOS."
